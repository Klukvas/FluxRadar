/** «1 пункт», «2 пункта», «5 пунктов»: what a Free check counts on a homepage. */
const ruItems = (count: number): string => ruCountForm(count, 'пункт', 'пункта', 'пунктов');

/**
 * «Найдена 1 проблема», «Найдено 2 проблемы», «Найдено 5 проблем».
 *
 * The participle agrees with the numeral as well as the noun, so the singular
 * is a sentence of its own rather than one of three noun forms.
 */
const ruProblemsFound = (count: number): string =>
  takesRuSingular(count)
    ? `Найдена ${count} проблема`
    : `Найдено ${count} ${ruCountForm(count, 'проблема', 'проблемы', 'проблем')}`;

