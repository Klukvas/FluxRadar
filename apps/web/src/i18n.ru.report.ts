// The Russian report screen: the chrome the app writes around the report.
//
// Everything here is interface. The report's own words — a rule's name, a
// finding's evidence, its recommendation, the AI and Bing observations — are
// written in the report's language and stay Ukrainian for a Russian reader;
// `report-language.ts` states where that line runs. Two catalogues that belong
// to `checks` are therefore missing from `russianReportChecksCopy` and spliced
// in from the Ukrainian branch by `i18n.ts`.
//
// Written from the Ukrainian meaning rather than word for word, and it keeps
// the locale's habits: no dash carrying a sentence, no accent on what the Free
// check costs, and nothing said about how the AI questions are built.

